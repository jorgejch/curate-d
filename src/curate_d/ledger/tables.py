"""Ledger schema.

Enumerations are stored as text with a CHECK constraint rather than as PostgreSQL enum
types: adding a value to a native enum needs ALTER TYPE outside a transaction on older
servers, and the constraint form keeps the allowed set visible in the table definition.

Timestamps are all timezone-aware. A naive timestamp on a file's modification time is a
silent correctness bug the moment two providers disagree about local time.
"""

