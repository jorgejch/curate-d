# Explicit naming so that autogenerated migrations produce stable constraint names and a
# downgrade can drop what an upgrade created.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata = MetaData(naming_convention=NAMING_CONVENTION)


def enum_check(column: str, *members: str) -> str:
    """SQL fragment restricting a text column to an enumeration's members."""
    allowed = ", ".join(f"'{value}'" for value in members)
    return f"{column} IN ({allowed})"


